-- ============================================================================
-- MIGRACIÓN INCREMENTAL 06: Separación de Ejercicios y Rutinas
-- (Personal del Socio vs Catálogo/Asignaciones del Gimnasio)
--
-- Reglas estructurales aprobadas:
--   - Sin columnas nullable excluyentes para representar propiedad.
--   - Separación estricta:
--       * ejercicio_socio -> rutina_ejercicio_socio -> rutina_socio
--       * ejercicio_gimnasio -> rutina_ejercicio_gimnasio -> rutina_gimnasio
--   - FKs compuestas garantizan en esquema que:
--       * rutina_socio solo use ejercicio_socio del mismo id_socio.
--       * rutina_gimnasio solo use ejercicio_gimnasio del mismo id_gimnasio.
--       * rutinas_asignadas_socio_gimnasio vincule rutina_gimnasio y
--         socio_gimnasio del mismo id_gimnasio.
--   - Conserva tablas previas (ejercicio, rutina, rutina_ejercicio) sin
--     DROP TABLE ni pérdida de historial durante la transición.
--
-- NO ejecutar sobre Supabase remoto sin aprobación/ventana controlada.
-- Ejecutar DESPUÉS de 05_socio_gimnasio_y_administradores.sql.
-- ============================================================================

begin;

-- ----------------------------------------------------------------------------
-- 1. Ejercicios separados por propietario
-- ----------------------------------------------------------------------------
create table if not exists public.ejercicio_socio (
  id_ejercicio_socio bigint generated by default as identity primary key,
  id_socio bigint not null references public.socio(id_socio) on delete cascade,
  nombre varchar(120) not null,
  descripcion text,
  grupo_muscular varchar(60),
  dificultad varchar(30),
  estado boolean not null default true,
  creado_en timestamptz not null default now(),
  constraint uq_ejercicio_socio_pk_owner unique (id_ejercicio_socio, id_socio)
);

create index if not exists idx_ejercicio_socio_socio
  on public.ejercicio_socio(id_socio, estado);

create table if not exists public.ejercicio_gimnasio (
  id_ejercicio_gimnasio bigint generated by default as identity primary key,
  id_gimnasio bigint not null references public.gimnasio(id_gimnasio) on delete cascade,
  nombre varchar(120) not null,
  descripcion text,
  grupo_muscular varchar(60),
  dificultad varchar(30),
  estado boolean not null default true,
  creado_en timestamptz not null default now(),
  constraint uq_ejercicio_gimnasio_pk_gym unique (id_ejercicio_gimnasio, id_gimnasio)
);

create index if not exists idx_ejercicio_gimnasio_gimnasio
  on public.ejercicio_gimnasio(id_gimnasio, estado);

-- ----------------------------------------------------------------------------
-- 2. Rutinas separadas por propietario
-- ----------------------------------------------------------------------------
create table if not exists public.rutina_socio (
  id_rutina_socio bigint generated by default as identity primary key,
  id_socio bigint not null references public.socio(id_socio) on delete cascade,
  nombre varchar(120) not null,
  descripcion text,
  fecha_inicio date,
  fecha_fin date,
  estado boolean not null default true,
  creado_en timestamptz not null default now(),
  constraint ck_fechas_rutina_socio check (fecha_fin is null or fecha_inicio is null or fecha_fin >= fecha_inicio),
  constraint uq_rutina_socio_pk_owner unique (id_rutina_socio, id_socio)
);

create index if not exists idx_rutina_socio_socio
  on public.rutina_socio(id_socio, estado);

create table if not exists public.rutina_gimnasio (
  id_rutina_gimnasio bigint generated by default as identity primary key,
  id_gimnasio bigint not null references public.gimnasio(id_gimnasio) on delete cascade,
  nombre varchar(120) not null,
  descripcion text,
  nivel varchar(40),
  estado boolean not null default true,
  creado_en timestamptz not null default now(),
  constraint uq_rutina_gimnasio_pk_gym unique (id_rutina_gimnasio, id_gimnasio)
);

create index if not exists idx_rutina_gimnasio_gimnasio
  on public.rutina_gimnasio(id_gimnasio, estado);

-- ----------------------------------------------------------------------------
-- 3. Tablas intermedias separadas con FKs compuestas anti-cruce
-- ----------------------------------------------------------------------------
create table if not exists public.rutina_ejercicio_socio (
  id_rutina_ejercicio_socio bigint generated by default as identity primary key,
  id_rutina_socio bigint not null,
  id_socio bigint not null,
  id_ejercicio_socio bigint not null,
  series integer not null check (series > 0),
  repeticiones integer not null check (repeticiones > 0),
  peso numeric(8,2) check (peso is null or peso >= 0),
  descanso integer check (descanso is null or descanso >= 0),
  orden integer not null check (orden > 0),
  constraint uq_ejercicio_en_rutina_socio unique (id_rutina_socio, id_ejercicio_socio),
  constraint uq_orden_en_rutina_socio unique (id_rutina_socio, orden),
  constraint fk_res_rutina_socio foreign key (id_rutina_socio, id_socio)
    references public.rutina_socio(id_rutina_socio, id_socio) on delete cascade,
  constraint fk_res_ejercicio_socio foreign key (id_ejercicio_socio, id_socio)
    references public.ejercicio_socio(id_ejercicio_socio, id_socio) on delete restrict
);

create index if not exists idx_res_rutina on public.rutina_ejercicio_socio(id_rutina_socio, orden);
create index if not exists idx_res_ejercicio on public.rutina_ejercicio_socio(id_ejercicio_socio);

create table if not exists public.rutina_ejercicio_gimnasio (
  id_rutina_ejercicio_gimnasio bigint generated by default as identity primary key,
  id_rutina_gimnasio bigint not null,
  id_gimnasio bigint not null,
  id_ejercicio_gimnasio bigint not null,
  series integer not null check (series > 0),
  repeticiones integer not null check (repeticiones > 0),
  peso numeric(8,2) check (peso is null or peso >= 0),
  descanso integer check (descanso is null or descanso >= 0),
  orden integer not null check (orden > 0),
  constraint uq_ejercicio_en_rutina_gimnasio unique (id_rutina_gimnasio, id_ejercicio_gimnasio),
  constraint uq_orden_en_rutina_gimnasio unique (id_rutina_gimnasio, orden),
  constraint fk_reg_rutina_gym foreign key (id_rutina_gimnasio, id_gimnasio)
    references public.rutina_gimnasio(id_rutina_gimnasio, id_gimnasio) on delete cascade,
  constraint fk_reg_ejercicio_gym foreign key (id_ejercicio_gimnasio, id_gimnasio)
    references public.ejercicio_gimnasio(id_ejercicio_gimnasio, id_gimnasio) on delete restrict
);

create index if not exists idx_reg_rutina on public.rutina_ejercicio_gimnasio(id_rutina_gimnasio, orden);
create index if not exists idx_reg_ejercicio on public.rutina_ejercicio_gimnasio(id_ejercicio_gimnasio);

-- ----------------------------------------------------------------------------
-- 4. Asignación de rutinas del gimnasio a socios (sin duplicar rutinas)
-- ----------------------------------------------------------------------------
create table if not exists public.rutinas_asignadas_socio_gimnasio (
  id_rutina_asignada bigint generated by default as identity primary key,
  id_rutina_gimnasio bigint not null,
  id_socio_gimnasio bigint not null,
  id_gimnasio bigint not null,
  id_empleado_responsable bigint references public.empleado(id_empleado) on delete set null,
  fecha_asignacion date not null default current_date,
  fecha_finalizacion date,
  estado boolean not null default true,
  observaciones text,
  creado_en timestamptz not null default now(),
  constraint ck_fechas_asignacion_rutina check (fecha_finalizacion is null or fecha_finalizacion >= fecha_asignacion),
  constraint fk_rasg_rutina_gym foreign key (id_rutina_gimnasio, id_gimnasio)
    references public.rutina_gimnasio(id_rutina_gimnasio, id_gimnasio) on delete restrict,
  constraint fk_rasg_socio_gym foreign key (id_socio_gimnasio, id_gimnasio)
    references public.socio_gimnasio(id_socio_gimnasio, id_gimnasio) on delete restrict
);

create unique index if not exists uq_rutina_asignada_activa
  on public.rutinas_asignadas_socio_gimnasio (id_rutina_gimnasio, id_socio_gimnasio)
  where estado = true;

create index if not exists idx_rasg_socio_gym
  on public.rutinas_asignadas_socio_gimnasio(id_socio_gimnasio, estado);

create index if not exists idx_rasg_rutina_gym
  on public.rutinas_asignadas_socio_gimnasio(id_rutina_gimnasio, estado);

-- ----------------------------------------------------------------------------
-- 5. Triggers de inmutabilidad de propietario y coherencia de asignación
-- ----------------------------------------------------------------------------
create or replace function public.trg_fn_proteger_propietario_ejercicio_sep()
returns trigger
language plpgsql
set search_path = pg_catalog, public
as $$
begin
  if tg_table_name = 'ejercicio_socio' then
    if new.id_ejercicio_socio is distinct from old.id_ejercicio_socio
       or new.id_socio is distinct from old.id_socio then
      raise exception 'No está permitido transferir un ejercicio_socio a otro socio.';
    end if;
  elsif tg_table_name = 'ejercicio_gimnasio' then
    if new.id_ejercicio_gimnasio is distinct from old.id_ejercicio_gimnasio
       or new.id_gimnasio is distinct from old.id_gimnasio then
      raise exception 'No está permitido transferir un ejercicio_gimnasio a otro gimnasio.';
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists trg_proteger_ejercicio_socio on public.ejercicio_socio;
create trigger trg_proteger_ejercicio_socio
before update on public.ejercicio_socio
for each row execute function public.trg_fn_proteger_propietario_ejercicio_sep();

drop trigger if exists trg_proteger_ejercicio_gimnasio on public.ejercicio_gimnasio;
create trigger trg_proteger_ejercicio_gimnasio
before update on public.ejercicio_gimnasio
for each row execute function public.trg_fn_proteger_propietario_ejercicio_sep();

create or replace function public.trg_fn_proteger_propietario_rutina_sep()
returns trigger
language plpgsql
set search_path = pg_catalog, public
as $$
begin
  if tg_table_name = 'rutina_socio' then
    if new.id_rutina_socio is distinct from old.id_rutina_socio
       or new.id_socio is distinct from old.id_socio then
      raise exception 'No está permitido cambiar el socio titular de una rutina_socio.';
    end if;
  elsif tg_table_name = 'rutina_gimnasio' then
    if new.id_rutina_gimnasio is distinct from old.id_rutina_gimnasio
       or new.id_gimnasio is distinct from old.id_gimnasio then
      raise exception 'No está permitido cambiar el gimnasio titular de una rutina_gimnasio.';
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists trg_proteger_rutina_socio on public.rutina_socio;
create trigger trg_proteger_rutina_socio
before update on public.rutina_socio
for each row execute function public.trg_fn_proteger_propietario_rutina_sep();

drop trigger if exists trg_proteger_rutina_gimnasio on public.rutina_gimnasio;
create trigger trg_proteger_rutina_gimnasio
before update on public.rutina_gimnasio
for each row execute function public.trg_fn_proteger_propietario_rutina_sep();

create or replace function public.trg_fn_validar_rutina_asignada()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_sg_estado boolean;
  v_rg_estado boolean;
  v_emp_gym bigint;
  v_emp_estado boolean;
  v_es_entrenador_o_admin boolean;
begin
  if tg_op = 'UPDATE' then
    if new.id_rutina_asignada is distinct from old.id_rutina_asignada
       or new.id_rutina_gimnasio is distinct from old.id_rutina_gimnasio
       or new.id_socio_gimnasio is distinct from old.id_socio_gimnasio
       or new.id_gimnasio is distinct from old.id_gimnasio then
      raise exception 'No se puede reasignar una fila de rutinas_asignadas_socio_gimnasio a otro socio, rutina o gimnasio.';
    end if;
  end if;

  if new.estado = true then
    select sg.estado into v_sg_estado
    from public.socio_gimnasio sg
    where sg.id_socio_gimnasio = new.id_socio_gimnasio
      and sg.id_gimnasio = new.id_gimnasio;

    if coalesce(v_sg_estado, false) = false then
      raise exception 'No se puede asignar rutina: la asociación socio_gimnasio (%) no está activa en el gimnasio %.', new.id_socio_gimnasio, new.id_gimnasio;
    end if;

    select rg.estado into v_rg_estado
    from public.rutina_gimnasio rg
    where rg.id_rutina_gimnasio = new.id_rutina_gimnasio
      and rg.id_gimnasio = new.id_gimnasio;

    if coalesce(v_rg_estado, false) = false then
      raise exception 'La rutina de gimnasio (%) no está activa.', new.id_rutina_gimnasio;
    end if;
  end if;

  if new.id_empleado_responsable is not null then
    select e.id_gimnasio, e.estado into v_emp_gym, v_emp_estado
    from public.empleado e
    where e.id_empleado = new.id_empleado_responsable;

    if not found or coalesce(v_emp_estado, false) = false or v_emp_gym <> new.id_gimnasio then
      raise exception 'El empleado responsable (%) no está activo o no pertenece al gimnasio %.', new.id_empleado_responsable, new.id_gimnasio;
    end if;

    select exists (
      select 1
      from public.empleado_sucursal es
      join public.sucursal s on s.id_sucursal = es.id_sucursal
      where es.id_empleado = new.id_empleado_responsable
        and es.estado = true
        and s.id_gimnasio = new.id_gimnasio
        and pg_catalog.lower(es.rol) in ('entrenador', 'administrador')
    ) into v_es_entrenador_o_admin;

    if not coalesce(v_es_entrenador_o_admin, false) then
      raise exception 'El empleado responsable (%) debe desempeñar rol entrenador o administrador en una sucursal del gimnasio.', new.id_empleado_responsable;
    end if;
  end if;

  return new;
end;
$$;

drop trigger if exists trg_validar_rutina_asignada on public.rutinas_asignadas_socio_gimnasio;
create trigger trg_validar_rutina_asignada
before insert or update on public.rutinas_asignadas_socio_gimnasio
for each row execute function public.trg_fn_validar_rutina_asignada();

revoke all on function public.trg_fn_proteger_propietario_ejercicio_sep() from public, anon, authenticated;
revoke all on function public.trg_fn_proteger_propietario_rutina_sep() from public, anon, authenticated;
revoke all on function public.trg_fn_validar_rutina_asignada() from public, anon, authenticated;

-- ----------------------------------------------------------------------------
-- 6. Migración segura e idempotente de datos previos desde tablas legacy
--    (NO elimina public.ejercicio, public.rutina ni public.rutina_ejercicio)
-- ----------------------------------------------------------------------------
do $$
declare
  v_cruces_omitidos bigint := 0;
begin
  -- 6a. Ejercicios personales -> ejercicio_socio
  if to_regclass('public.ejercicio') is not null
     and not exists (select 1 from public.ejercicio_socio)
     and exists (select 1 from public.ejercicio where id_socio is not null) then
    insert into public.ejercicio_socio (id_socio, nombre, descripcion, grupo_muscular, dificultad, estado)
    select id_socio, nombre, descripcion, grupo_muscular, dificultad, true
    from public.ejercicio
    where id_socio is not null and id_gimnasio is null;
  end if;

  -- 6b. Ejercicios del gimnasio -> ejercicio_gimnasio
  if to_regclass('public.ejercicio') is not null
     and not exists (select 1 from public.ejercicio_gimnasio)
     and exists (select 1 from public.ejercicio where id_gimnasio is not null) then
    insert into public.ejercicio_gimnasio (id_gimnasio, nombre, descripcion, grupo_muscular, dificultad, estado)
    select id_gimnasio, nombre, descripcion, grupo_muscular, dificultad, true
    from public.ejercicio
    where id_gimnasio is not null and id_socio is null;
  end if;

  -- 6c. Rutinas personales -> rutina_socio y sus ejercicios personales -> rutina_ejercicio_socio
  if to_regclass('public.rutina') is not null
     and not exists (select 1 from public.rutina_socio)
     and exists (select 1 from public.rutina) then
    create temp table tmp_map_rutinas (
      old_id bigint primary key,
      new_id bigint not null,
      id_socio bigint not null
    ) on commit drop;

    with ins_r as (
      insert into public.rutina_socio (id_socio, nombre, descripcion, fecha_inicio, fecha_fin, estado)
      select r.id_socio, r.nombre, r.descripcion, r.fecha_inicio, r.fecha_fin, r.estado
      from public.rutina r
      order by r.id_rutina
      returning id_rutina_socio, id_socio, nombre
    )
    insert into tmp_map_rutinas (old_id, new_id, id_socio)
    select distinct on (r.id_rutina) r.id_rutina, ir.id_rutina_socio, r.id_socio
    from public.rutina r
    join ins_r ir on ir.id_socio = r.id_socio and ir.nombre = r.nombre;

    if to_regclass('public.rutina_ejercicio') is not null then
      insert into public.rutina_ejercicio_socio (
        id_rutina_socio, id_socio, id_ejercicio_socio, series, repeticiones, peso, descanso, orden
      )
      select
        mr.new_id,
        mr.id_socio,
        es.id_ejercicio_socio,
        re.series,
        re.repeticiones,
        re.peso,
        re.descanso,
        row_number() over (partition by mr.new_id order by re.orden)
      from public.rutina_ejercicio re
      join tmp_map_rutinas mr on mr.old_id = re.id_rutina
      join public.ejercicio e on e.id_ejercicio = re.id_ejercicio
      join public.ejercicio_socio es
        on es.id_socio = e.id_socio
       and es.nombre = e.nombre
      where e.id_socio = mr.id_socio
      on conflict do nothing;

      select count(*) into v_cruces_omitidos
      from public.rutina_ejercicio re
      join public.ejercicio e on e.id_ejercicio = re.id_ejercicio
      where e.id_gimnasio is not null;

      if v_cruces_omitidos > 0 then
        raise notice 'Se detectaron % asociaciones legacy rutina_socio <-> ejercicio de gimnasio conservadas en las tablas legacy (regla nueva exige separación estricta).', v_cruces_omitidos;
      end if;
    end if;
  end if;
end $$;

