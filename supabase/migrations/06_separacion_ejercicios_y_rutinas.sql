alter table public.ejercicio_socio enable row level security;
alter table public.ejercicio_gimnasio enable row level security;
alter table public.rutina_socio enable row level security;
alter table public.rutina_gimnasio enable row level security;
alter table public.rutina_ejercicio_socio enable row level security;
alter table public.rutina_ejercicio_gimnasio enable row level security;
alter table public.rutinas_asignadas_socio_gimnasio enable row level security;

revoke all on
  public.ejercicio_socio,
  public.ejercicio_gimnasio,
  public.rutina_socio,
  public.rutina_gimnasio,
  public.rutina_ejercicio_socio,
  public.rutina_ejercicio_gimnasio,
  public.rutinas_asignadas_socio_gimnasio
from public, anon, authenticated;

commit;
