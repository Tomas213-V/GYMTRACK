-- ============================================================================
-- MIGRACIÓN INCREMENTAL 05: Asociaciones socio_gimnasio, Evolución de
-- membresia_socio hacia socio_gimnasio, y Entidades administrador /
-- administrador_gimnasio.
--
-- Alcance:
--   1. Crea public.socio_gimnasio con UNIQUE(id_socio, id_gimnasio) y
--      UNIQUE(id_socio_gimnasio, id_gimnasio) para FKs compuestas.
--   2. Migra sin pérdida de datos todas las relaciones históricas existentes
--      desde public.membresia_socio hacia public.socio_gimnasio.
--   3. Evoluciona public.membresia_socio para referenciar (id_socio_gimnasio,
--      id_gimnasio) en lugar de id_socio directamente, audita dependencias y
--      elimina la columna redundante id_socio sin CASCADE.
--   4. Crea public.administrador y public.administrador_gimnasio (N:M) con
--      identidad única Supabase Auth y triggers de protección.
--
-- NO ejecutar sobre Supabase remoto sin aprobación/ventana controlada.
-- Ejecutar DESPUÉS de 04_simplificar_asistencia_socio.sql.
-- ============================================================================

begin;

-- ----------------------------------------------------------------------------
-- 1. Crear public.socio_gimnasio (asociación independiente de contrataciones)
-- ----------------------------------------------------------------------------
create table if not exists public.socio_gimnasio (
  id_socio_gimnasio bigint generated by default as identity primary key,
  id_socio bigint not null references public.socio(id_socio) on delete restrict,
  id_gimnasio bigint not null references public.gimnasio(id_gimnasio) on delete restrict,
  fecha_alta date not null default current_date,
  estado boolean not null default true,
  creado_en timestamptz not null default now(),
  constraint uq_socio_gimnasio unique (id_socio, id_gimnasio),
  constraint uq_socio_gimnasio_id_gym unique (id_socio_gimnasio, id_gimnasio)
);

create index if not exists idx_socio_gimnasio_gimnasio
  on public.socio_gimnasio(id_gimnasio, estado);

create index if not exists idx_socio_gimnasio_socio
  on public.socio_gimnasio(id_socio, estado);

-- Trigger de inmutabilidad en socio_gimnasio: no cambiar titular ni gimnasio
create or replace function public.trg_fn_proteger_socio_gimnasio()
returns trigger
language plpgsql
set search_path = pg_catalog, public, auth
as $$
declare
  v_jwt_role text := coalesce(nullif(pg_catalog.current_setting('request.jwt.claim.role', true), ''), '');
begin
  if v_jwt_role = 'service_role' or (pg_catalog.current_user in ('postgres', 'supabase_admin', 'service_role') and auth.uid() is null) then
    return new;
  end if;

  if new.id_socio_gimnasio is distinct from old.id_socio_gimnasio
     or new.id_socio is distinct from old.id_socio
     or new.id_gimnasio is distinct from old.id_gimnasio
     or new.fecha_alta is distinct from old.fecha_alta
     or new.creado_en is distinct from old.creado_en then
    raise exception 'No está permitido reasignar el socio, el gimnasio ni la fecha de alta de una asociación socio_gimnasio.';
  end if;

  return new;
end;
$$;

drop trigger if exists trg_proteger_socio_gimnasio on public.socio_gimnasio;
create trigger trg_proteger_socio_gimnasio
before update on public.socio_gimnasio
for each row
execute function public.trg_fn_proteger_socio_gimnasio();

revoke all on function public.trg_fn_proteger_socio_gimnasio() from public, anon, authenticated;

-- ----------------------------------------------------------------------------
-- 2. Backfill y evolución de public.membresia_socio -> socio_gimnasio
-- ----------------------------------------------------------------------------
do $$
declare
  v_has_id_socio boolean;
  v_pendientes bigint;
begin
  select exists (
    select 1
    from pg_catalog.pg_attribute
    where attrelid = 'public.membresia_socio'::regclass
      and attname = 'id_socio'
      and not attisdropped
  ) into v_has_id_socio;

  if v_has_id_socio then
    -- Poblar socio_gimnasio con todas las contrataciones previas (conservando la fecha más antigua)
    insert into public.socio_gimnasio (id_socio, id_gimnasio, fecha_alta, estado)
    select
      ms.id_socio,
      ms.id_gimnasio,
      coalesce(min(ms.creado_en)::date, min(ms.fecha_inicio), current_date),
      true
    from public.membresia_socio ms
    group by ms.id_socio, ms.id_gimnasio
    on conflict (id_socio, id_gimnasio) do nothing;
  end if;

  -- Añadir id_socio_gimnasio a public.membresia_socio si aún no existe
  if not exists (
    select 1
    from pg_catalog.pg_attribute
    where attrelid = 'public.membresia_socio'::regclass
      and attname = 'id_socio_gimnasio'
      and not attisdropped
  ) then
    alter table public.membresia_socio
      add column id_socio_gimnasio bigint;
  end if;

  if v_has_id_socio then
    update public.membresia_socio ms
    set id_socio_gimnasio = sg.id_socio_gimnasio
    from public.socio_gimnasio sg
    where sg.id_socio = ms.id_socio
      and sg.id_gimnasio = ms.id_gimnasio
      and ms.id_socio_gimnasio is null;
  end if;

  select count(*) into v_pendientes
  from public.membresia_socio
  where id_socio_gimnasio is null;

  if v_pendientes > 0 then
    raise exception 'Existen % filas en membresia_socio sin correspondencia en socio_gimnasio. Abortando migración 05.', v_pendientes;
  end if;
end $$;

alter table public.membresia_socio
  alter column id_socio_gimnasio set not null;

do $$
begin
  if not exists (
    select 1
    from pg_catalog.pg_constraint c
    where c.conrelid = 'public.membresia_socio'::regclass
      and c.conname = 'fk_contrato_socio_gimnasio'
  ) then
    alter table public.membresia_socio
      add constraint fk_contrato_socio_gimnasio
      foreign key (id_socio_gimnasio, id_gimnasio)
      references public.socio_gimnasio(id_socio_gimnasio, id_gimnasio)
      on delete restrict;
  end if;
end $$;

create index if not exists idx_contrato_socio_gimnasio
  on public.membresia_socio(id_socio_gimnasio, estado, fecha_vencimiento desc);

-- Actualizar trigger de socio y políticas que referenciaban membresia_socio.id_socio ANTES de retirar esa columna
create or replace function public.trg_fn_proteger_campos_socio()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public, auth
as $$
declare
  v_uid uuid := auth.uid();
  v_jwt_role text := coalesce(nullif(pg_catalog.current_setting('request.jwt.claim.role', true), ''), '');
  v_es_dueno_o_admin boolean := false;
begin
  if v_jwt_role = 'service_role' or (pg_catalog.current_user in ('postgres', 'supabase_admin', 'service_role') and v_uid is null) then
    return new;
  end if;

  if new.id_socio is distinct from old.id_socio then
    raise exception 'No se puede modificar el identificador del socio.';
  end if;

  if new.auth_user_id is distinct from old.auth_user_id then
    raise exception 'No tienes autorización para modificar auth_user_id del socio.';
  end if;

  if new.fecha_alta is distinct from old.fecha_alta then
    raise exception 'No se puede modificar la fecha de alta administrativa del socio.';
  end if;

  if new.estado is distinct from old.estado then
    select (
      exists (
        select 1
        from public.socio_gimnasio sg
        join public.gimnasio g on g.id_gimnasio = sg.id_gimnasio
        join public.dueno d on d.id_dueno = g.id_dueno
        where sg.id_socio = old.id_socio
          and d.auth_user_id = v_uid
      )
      or exists (
        select 1
        from public.socio_gimnasio sg
        join public.empleado e on e.id_gimnasio = sg.id_gimnasio
        join public.empleado_sucursal es on es.id_empleado = e.id_empleado
        join public.sucursal s on s.id_sucursal = es.id_sucursal and s.id_gimnasio = sg.id_gimnasio
        where sg.id_socio = old.id_socio
          and e.auth_user_id = v_uid
          and e.estado = true
          and es.estado = true
          and pg_catalog.lower(es.rol) = 'administrador'
      )
    ) into v_es_dueno_o_admin;

    if not coalesce(v_es_dueno_o_admin, false) then
      raise exception 'Solo el dueño o administrador autorizado del gimnasio puede cambiar el estado del socio.';
    end if;
  end if;

  return new;
end;
$$;

revoke all on function public.trg_fn_proteger_campos_socio() from public, anon, authenticated;

