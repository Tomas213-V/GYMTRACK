-- Auditar y eliminar restricciones/índices que dependan de membresia_socio.id_socio sin CASCADE
do $$
declare
  v_attnum smallint;
  v_idx record;
  v_con record;
  v_dep record;
begin
  select attnum into v_attnum
  from pg_catalog.pg_attribute
  where attrelid = 'public.membresia_socio'::regclass
    and attname = 'id_socio'
    and not attisdropped;

  if v_attnum is not null then
    for v_idx in
      select ns.nspname as schema_name, cls.relname as index_name
      from pg_catalog.pg_index ix
      join pg_catalog.pg_class cls on cls.oid = ix.indexrelid
      join pg_catalog.pg_namespace ns on ns.oid = cls.relnamespace
      where ix.indrelid = 'public.membresia_socio'::regclass
        and not ix.indisprimary
        and v_attnum = any(ix.indkey::smallint[])
        and not exists (select 1 from pg_catalog.pg_constraint c where c.conindid = ix.indexrelid)
    loop
      execute format('drop index if exists %I.%I', v_idx.schema_name, v_idx.index_name);
    end loop;

    for v_con in
      select c.conname
      from pg_catalog.pg_constraint c
      where c.conrelid = 'public.membresia_socio'::regclass
        and v_attnum = any(c.conkey)
    loop
      execute format('alter table public.membresia_socio drop constraint if exists %I', v_con.conname);
    end loop;

    for v_dep in
      select d.classid::regclass::text as obj_class, d.objid
      from pg_catalog.pg_depend d
      where d.refobjid = 'public.membresia_socio'::regclass
        and d.refobjsubid = v_attnum
        and d.deptype in ('n', 'a')
    loop
      raise exception 'Dependencia residual detectada sobre membresia_socio.id_socio (clase: %, objid: %). Abortando para evitar pérdida.', v_dep.obj_class, v_dep.objid;
    end loop;
  end if;
end $$;

alter table public.membresia_socio
