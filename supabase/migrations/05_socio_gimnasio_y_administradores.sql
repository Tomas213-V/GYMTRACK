create table if not exists public.administrador_gimnasio (
  id_administrador_gimnasio bigint generated by default as identity primary key,
  id_administrador bigint not null references public.administrador(id_administrador) on delete restrict,
  id_gimnasio bigint not null references public.gimnasio(id_gimnasio) on delete restrict,
  fecha_asignacion timestamptz not null default now(),
  estado boolean not null default true,
  constraint uq_administrador_gimnasio unique (id_administrador, id_gimnasio)
);

create index if not exists idx_administrador_auth_user
  on public.administrador(auth_user_id);

