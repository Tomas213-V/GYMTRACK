create or replace function public.trg_fn_proteger_campos_administrador()
returns trigger language plpgsql set search_path = pg_catalog, public, auth as $$
declare v_uid uuid := auth.uid(); v_jwt_role text := coalesce(nullif(pg_catalog.current_setting('request.jwt.claim.role', true), ''), ''); v_es_dueno boolean := false;
begin
  if v_jwt_role = 'service_role' or (pg_catalog.current_user in ('postgres', 'supabase_admin', 'service_role') and v_uid is null) then return new; end if;
  if new.id_administrador is distinct from old.id_administrador or new.auth_user_id is distinct from old.auth_user_id or new.fecha_creacion is distinct from old.fecha_creacion then
    raise exception 'No puedes alterar identidad ni fecha_creacion del administrador.';
  end if;
  if new.estado is distinct from old.estado then
    select exists (select 1 from public.administrador_gimnasio ag join public.gimnasio g on g.id_gimnasio = ag.id_gimnasio join public.dueno d on d.id_dueno = g.id_dueno where ag.id_administrador = old.id_administrador and d.auth_user_id = v_uid) into v_es_dueno;
    if not coalesce(v_es_dueno, false) then raise exception 'Solo el dueño puede activar o desactivar al administrador.'; end if;
  end if;
  return new;
end;
$$;
create trigger trg_proteger_campos_administrador before update on public.administrador for each row execute function public.trg_fn_proteger_campos_administrador();

