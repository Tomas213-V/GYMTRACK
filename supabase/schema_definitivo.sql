-- 10. Triggers de integridad estructural y anti-manipulación (Escenario A)
create or replace function public.trg_fn_proteger_empleado_gimnasio_cambio()
returns trigger language plpgsql set search_path = pg_catalog, public as $$
begin
  if new.id_gimnasio is distinct from old.id_gimnasio then
    if exists (
      select 1 from public.empleado_sucursal es
      join public.sucursal s on s.id_sucursal = es.id_sucursal
      where es.id_empleado = old.id_empleado and s.id_gimnasio is distinct from new.id_gimnasio
    ) then
      raise exception 'No se puede cambiar el gimnasio del empleado % mientras tenga sucursales de otro gimnasio.', old.id_empleado;
    end if;
  end if;
  return new;
end;
$$;
create trigger trg_proteger_empleado_gimnasio_cambio before update of id_gimnasio on public.empleado for each row execute function public.trg_fn_proteger_empleado_gimnasio_cambio();

create or replace function public.trg_fn_validar_empleado_sucursal_gimnasio()
returns trigger language plpgsql security definer set search_path = pg_catalog, public as $$
declare v_emp_gym bigint; v_suc_gym bigint;
begin
  select e.id_gimnasio into v_emp_gym from public.empleado e where e.id_empleado = new.id_empleado;
  if not found or v_emp_gym is null then raise exception 'Empleado % inválido o sin gimnasio.', new.id_empleado; end if;
  select s.id_gimnasio into v_suc_gym from public.sucursal s where s.id_sucursal = new.id_sucursal;
  if not found or v_suc_gym is null then raise exception 'Sucursal % inválida.', new.id_sucursal; end if;
  if v_emp_gym <> v_suc_gym then raise exception 'No se permite asignar empleado del gimnasio % a sucursal del gimnasio %.', v_emp_gym, v_suc_gym; end if;
  new.rol := pg_catalog.lower(pg_catalog.btrim(new.rol));
  return new;
end;
$$;
create trigger trg_validar_empleado_sucursal_gimnasio before insert or update on public.empleado_sucursal for each row execute function public.trg_fn_validar_empleado_sucursal_gimnasio();

create or replace function public.trg_fn_proteger_campos_dueno()
returns trigger language plpgsql set search_path = pg_catalog, public, auth as $$
declare v_jwt_role text := coalesce(nullif(pg_catalog.current_setting('request.jwt.claim.role', true), ''), '');
begin
  if v_jwt_role = 'service_role' or (pg_catalog.current_user in ('postgres', 'supabase_admin', 'service_role') and auth.uid() is null) then return new; end if;
  if new.id_dueno is distinct from old.id_dueno or new.auth_user_id is distinct from old.auth_user_id or new.fecha_creacion is distinct from old.fecha_creacion then
    raise exception 'No tienes autorización para modificar identidad o auditoría del dueño.';
  end if;
  return new;
end;
$$;
create trigger trg_proteger_campos_dueno before update on public.dueno for each row execute function public.trg_fn_proteger_campos_dueno();

