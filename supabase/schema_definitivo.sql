create or replace function public.trg_fn_validar_rutina_asignada()
returns trigger language plpgsql security definer set search_path = pg_catalog, public as $$
declare v_sg_estado boolean; v_rg_estado boolean; v_emp_gym bigint; v_emp_estado boolean; v_ok boolean;
begin
  if tg_op = 'UPDATE' and (new.id_rutina_asignada is distinct from old.id_rutina_asignada or new.id_rutina_gimnasio is distinct from old.id_rutina_gimnasio or new.id_socio_gimnasio is distinct from old.id_socio_gimnasio or new.id_gimnasio is distinct from old.id_gimnasio) then
    raise exception 'No se puede reasignar una asignación existente.';
  end if;
  if new.estado = true then
    select sg.estado into v_sg_estado from public.socio_gimnasio sg where sg.id_socio_gimnasio = new.id_socio_gimnasio and sg.id_gimnasio = new.id_gimnasio;
    if coalesce(v_sg_estado, false) = false then raise exception 'La asociación socio_gimnasio no está activa.'; end if;
    select rg.estado into v_rg_estado from public.rutina_gimnasio rg where rg.id_rutina_gimnasio = new.id_rutina_gimnasio and rg.id_gimnasio = new.id_gimnasio;
    if coalesce(v_rg_estado, false) = false then raise exception 'La rutina_gimnasio no está activa.'; end if;
  end if;
  if new.id_empleado_responsable is not null then
    select e.id_gimnasio, e.estado into v_emp_gym, v_emp_estado from public.empleado e where e.id_empleado = new.id_empleado_responsable;
    if not found or coalesce(v_emp_estado, false) = false or v_emp_gym <> new.id_gimnasio then raise exception 'Empleado responsable inválido para este gimnasio.'; end if;
    select exists (select 1 from public.empleado_sucursal es join public.sucursal s on s.id_sucursal = es.id_sucursal where es.id_empleado = new.id_empleado_responsable and es.estado = true and s.id_gimnasio = new.id_gimnasio and pg_catalog.lower(es.rol) in ('entrenador', 'administrador')) into v_ok;
    if not coalesce(v_ok, false) then raise exception 'Empleado responsable debe ser entrenador o administrador.'; end if;
  end if;
  return new;
end;
$$;
create trigger trg_validar_rutina_asignada before insert or update on public.rutinas_asignadas_socio_gimnasio for each row execute function public.trg_fn_validar_rutina_asignada();

