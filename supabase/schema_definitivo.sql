  if new.id_membresia_socio is distinct from old.id_membresia_socio or new.id_socio_gimnasio is distinct from old.id_socio_gimnasio or new.id_membresia_gimnasio is distinct from old.id_membresia_gimnasio or new.id_gimnasio is distinct from old.id_gimnasio or new.precio is distinct from old.precio or new.duracion_dias_contratados is distinct from old.duracion_dias_contratados or new.limite_asistencias_semanales is distinct from old.limite_asistencias_semanales or new.limite_asistencias_totales is distinct from old.limite_asistencias_totales or new.creado_en is distinct from old.creado_en then
    raise exception 'No se pueden alterar las condiciones históricas ni titulares de una membresía contratada.';
  end if;
